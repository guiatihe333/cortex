"""AMB-1 FM6's built-in DX7 banks: 16 bulk dumps (32 voices, VMEM) into app/bank_rom.h, the banks a fresh FM-1 has
until a bank of its own comes in (bank.c: a bank whose first slot is erased flash plays the built-in one).

  tools/gen_banks.py OUT.h BANK1.syx .. BANK16.syx"""
import sys
from pathlib import Path


def vmem(path):
    raw = Path(path).read_bytes()
    if len(raw) != 4104 or raw[:6] != bytes([0xF0, 0x43, 0x00, 0x09, 0x20, 0x00]) or raw[-1] != 0xF7:
        raise SystemExit(f"{path}: not a DX7 32-voice bulk dump")
    data = raw[6:6 + 4096]
    if (-sum(data)) & 0x7F != raw[6 + 4096]:
        raise SystemExit(f"{path}: bad checksum")
    return data


def main(out, *syx):
    if len(syx) != 16:
        raise SystemExit(__doc__)
    lines = ["/* generated by tools/gen_banks.py: AMB-1 FM6's built-in DX7 banks (32 voices each, as a DX7 packs them) */",
             "/* " + ", ".join(Path(p).stem for p in syx) + " */",
             "static const uint8_t BANK_ROM[16][4096] = {"]
    for p in syx:
        d = vmem(p)
        lines.append("    {")
        for i in range(0, 4096, 32):
            lines.append("        " + ",".join(str(b) for b in d[i:i + 32]) + ",")
        lines.append("    },")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"banks: {out} (16 x 32 voices)")


if __name__ == "__main__":
    main(*sys.argv[1:])
